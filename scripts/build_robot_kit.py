"""The robot kit for real2sim (docs/real2sim.md): the twin's model with the SCENE taken out, so that an agent that
reconstructs the scene from the robot's cameras cannot read it from the robot's own model files.

Kept (the robot, as its owner knows it): both arms (L_, R_; the right one parked), the gripper, the arm frame they
stand on, the scene D415's camera body and mount, the wrist D415, the actuators, the finger couplings, the physics
options, the headlight. Taken out: the table and its legs, the floor, the lights, the sky, the ruler and every object
(their meshes too). The vendored code needs the objects' bodies by name (task_box.BoxSim: obj_<k>, the white box's
floor geom and lid hinge, the geom table_top), so each stays as a PLACEHOLDER: the same body / joint names, one 4 mm
non-colliding invisible sphere per body, parked far behind the robot. The keyframe "twin" keeps the arms' joints.

    python scripts/build_robot_kit.py  ->  src/agentic_robotics/selfsim/models/robot_kit.xml"""
import xml.etree.ElementTree as ET
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "src/agentic_robotics/vendor/panda_twin/model/twin_6522_wedge.xml"
OUT = ROOT / "src/agentic_robotics/selfsim/models/robot_kit.xml"
KEEP_NAMED_GEOMS = {"obj_box_white_floor"}            # (task_box.BoxSim looks it up by name)
SCENE_GEOMS = ("table_top", "table_leg", "floor")
PARK = (3.0, 2.0, -0.80)


def placeholder(b, j, top):
    """A body of the scene -> the same names, joints and children, one invisible non-colliding sphere."""
    out = ET.Element("body", {"name": b.get("name")})
    out.set("pos", f"{PARK[0] + 0.35 * j:.3f} {PARK[1]:.3f} {PARK[2]:.3f}" if top else "0 0 0")
    for c in b:                                       # (names and kinds only: no sizes, ranges, damping or friction)
        if c.tag == "freejoint":
            out.append(ET.Element("freejoint", {"name": c.get("name")}))
        elif c.tag == "joint":
            out.append(ET.Element("joint", {k: c.get(k) for k in ("name", "type", "axis") if c.get(k)}))
    names = [g.get("name") for g in b if g.tag == "geom" and g.get("name") in KEEP_NAMED_GEOMS]
    for k, nm in enumerate(names or [None]):
        g = ET.SubElement(out, "geom", {"type": "sphere", "size": "0.004", "contype": "0", "conaffinity": "0",
                                        "group": "5", "rgba": "0 0 0 0", "mass": "0.005"})
        g.set("name", nm or f"{b.get('name')}_ph")
    for k, c in enumerate(x for x in b if x.tag == "body"):
        out.append(placeholder(c, k, False))
    return out


def main():
    import mujoco
    t = ET.parse(SRC); r = t.getroot()
    r.find("compiler").set("meshdir", "../../vendor/panda_twin/model/assets")
    a = r.find("asset")
    for c in list(a):
        if (c.tag == "mesh" and (c.get("file") or "").startswith("twin_6522/")) or (c.tag == "texture" and c.get("type") == "skybox"):
            a.remove(c)
    wb = r.find("worldbody")
    j = 0
    for c in list(wb):
        nm = c.get("name") or ""
        if c.tag == "light" or (c.tag == "geom" and nm.startswith(SCENE_GEOMS)):
            wb.remove(c)
        elif c.tag == "body" and nm.startswith("obj_"):
            i = list(wb).index(c); wb.remove(c); wb.insert(i, placeholder(c, j, True)); j += 1
    ET.SubElement(wb, "geom", {"name": "table_top", "type": "box", "size": "0.004 0.004 0.004", "pos": f"{PARK[0]} {PARK[1] + 0.5} {PARK[2]}",
                               "contype": "0", "conaffinity": "0", "group": "5", "rgba": "0 0 0 0"})
    key = r.find("keyframe"); r.remove(key)
    m0 = mujoco.MjModel.from_xml_path(str(SRC)); k0 = m0.key("twin").qpos
    OUT.parent.mkdir(parents=True, exist_ok=True)
    tmp = OUT.with_suffix(".tmp.xml"); t.write(tmp)
    m1 = mujoco.MjModel.from_xml_path(str(tmp))
    q = m1.qpos0.copy()
    for jn in range(m1.njnt):
        name = m1.joint(jn).name
        if name.startswith(("L_", "R_")):
            a0, a1 = m0.joint(name).qposadr[0], m1.joint(name).qposadr[0]
            q[a1] = k0[a0]
    ET.SubElement(ET.SubElement(r, "keyframe"), "key", {"name": "twin", "qpos": " ".join(f"{v:.6g}" for v in q)})
    ET.indent(t, "  ")
    txt = ET.tostring(r, encoding="unicode")
    OUT.write_text("<!-- GENERATED by scripts/build_robot_kit.py from the vendored twin_6522_wedge.xml: the robot only "
                   "(docs/real2sim.md). Do not edit. -->\n" + txt + "\n")
    tmp.unlink()
    m = mujoco.MjModel.from_xml_path(str(OUT))
    print(OUT, f"nbody {m.nbody} ngeom {m.ngeom} nq {m.nq} nmesh {m.nmesh} nlight {m.nlight}")


if __name__ == "__main__":
    main()
